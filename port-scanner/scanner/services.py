_SERVICES: dict[int, str] = dict(WELL_KNOWN)
_PATH = Path("/etc/services")
if _PATH.exists():
    try:
        for _line in _PATH.read_text(errors="ignore").splitlines():
            _line = _line.split("#", 1)[0].strip()
            if not _line:
                continue
            _parts = _line.split()
            if len(_parts) >= 2 and "/" in _parts[1]:
                _name, _port_proto = _parts[0], _parts[1]
                _port = _port_proto.split("/")[0]
                if _port.isdigit():
                    _port = int(_port)
                    if _port not in _SERVICES:
                        _SERVICES[_port] = _name
    except OSError:
        pass


def lookup_service(port: int) -> str:
    if port in _SERVICES:
        return _SERVICES[port]
    try:
        name = socket.getservbyport(port)
        if name:
            _SERVICES[port] = name
            return name
    except OSError:
        pass
    return "unknown"


